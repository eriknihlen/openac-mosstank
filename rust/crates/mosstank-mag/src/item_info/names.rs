//! The names Mag-Tools gives skills, weapon masteries, equipment sets and
//! materials, copied from Mag-Tools' `Shared/Constants/Dictionaries.cs`
//! (43ee2ec) as written there, typos and trailing spaces included.

/// The name of `id` in a table of `(id, name)`.
fn lookup(table: &[(i32, &'static str)], id: i32) -> Option<&'static str> {
    table.iter().find(|(k, _)| *k == id).map(|(_, v)| *v)
}

/// A skill's name (`SkillInfo`).
#[must_use]
pub fn skill(id: i32) -> Option<&'static str> {
    lookup(SKILL_INFO, id)
}

/// A weapon mastery's name (`MasteryInfo`).
#[must_use]
pub fn mastery(id: i32) -> Option<&'static str> {
    lookup(MASTERY_INFO, id)
}

/// An equipment set's name (`AttributeSetInfo`).
#[must_use]
pub fn attribute_set(id: i32) -> Option<&'static str> {
    lookup(ATTRIBUTE_SET_INFO, id)
}

/// A material's name (`MaterialInfo`).
#[must_use]
pub fn material(id: i32) -> Option<&'static str> {
    lookup(MATERIAL_INFO, id)
}

